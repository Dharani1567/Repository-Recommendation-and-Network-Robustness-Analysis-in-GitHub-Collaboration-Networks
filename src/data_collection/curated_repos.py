def get_all_target_repositories() -> list:
    """Return deduplicated list of target repositories across all domains."""
    seen = set()
    ordered = []
    for domain, repos in EXPANDED_SEED_REPOSITORIES.items():
        for r in repos:
            clean = r.strip().lower()
            if clean not in seen:
                seen.add(clean)
                ordered.append(r.strip())
    return ordered
